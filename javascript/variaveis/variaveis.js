// O que são variáveis em Javascript

// let; é usando quando determinada informação/dado/variável muda durante a execução do sistema/programa
// Exe.: Um sistema que faz conversão de moedas

// const; é usando quando determinada informação/dado/variável não muda durante a execução do sistema/programa
// Exe.: π caucula o raio de uma circunferencia e é um valor CONSTante

 // let name; let é o tipo de variável e "name" é o nome da variável.
let userName = "Gideão Ferreira"; // `= "Gideão"` valor declarado na variável.
userName = "Karol"


const user = "Karolina Melo"
console.log(user)